CREATE TABLE IF NOT EXISTS mes_order (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code VARCHAR(80) NOT NULL UNIQUE,
  target_qty INTEGER NOT NULL,
  status VARCHAR(32) NOT NULL,
  last_launched INTEGER NOT NULL DEFAULT 0,
  last_rejected INTEGER NOT NULL DEFAULT 0,
  last_packed INTEGER NOT NULL DEFAULT 0,
  last_exit INTEGER NOT NULL DEFAULT 0,
  loaded_qty INTEGER NOT NULL DEFAULT 0,
  dispatched_qty INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE mes_order ADD COLUMN IF NOT EXISTS run_base_launched INTEGER NOT NULL DEFAULT 0;
ALTER TABLE mes_order ADD COLUMN IF NOT EXISTS run_base_rejected INTEGER NOT NULL DEFAULT 0;
ALTER TABLE mes_order ADD COLUMN IF NOT EXISTS run_base_packed INTEGER NOT NULL DEFAULT 0;
ALTER TABLE mes_order ADD COLUMN IF NOT EXISTS run_base_exit INTEGER NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS inventory (
  sku VARCHAR(32) PRIMARY KEY,
  quantity INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS mes_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES mes_order(id),
  event_type VARCHAR(40) NOT NULL,
  counter_value INTEGER NOT NULL,
  occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT event_once UNIQUE (order_id, event_type, counter_value)
);

CREATE TABLE IF NOT EXISTS item_master (
  sku VARCHAR(32) PRIMARY KEY,
  item_name VARCHAR(100) NOT NULL,
  item_type VARCHAR(16) NOT NULL,
  unit VARCHAR(16) NOT NULL
);
CREATE TABLE IF NOT EXISTS bom_line (
  product_sku VARCHAR(32) NOT NULL REFERENCES item_master(sku),
  material_sku VARCHAR(32) NOT NULL REFERENCES item_master(sku),
  quantity_per_unit INTEGER NOT NULL,
  PRIMARY KEY (product_sku,material_sku)
);
CREATE TABLE IF NOT EXISTS material_lot (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_code VARCHAR(80) NOT NULL UNIQUE,
  sku VARCHAR(32) NOT NULL REFERENCES item_master(sku),
  supplier VARCHAR(120) NOT NULL,
  origin VARCHAR(120) NOT NULL,
  received_qty INTEGER NOT NULL,
  available_qty INTEGER NOT NULL,
  received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS material_issue (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES mes_order(id),
  launch_counter INTEGER NOT NULL,
  material_lot_id BIGINT NOT NULL REFERENCES material_lot(id),
  sku VARCHAR(32) NOT NULL,
  quantity INTEGER NOT NULL,
  issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT issue_once UNIQUE (order_id, launch_counter, sku)
);
CREATE TABLE IF NOT EXISTS production_plan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_code VARCHAR(80) NOT NULL UNIQUE,
  product_sku VARCHAR(32) NOT NULL REFERENCES item_master(sku),
  target_qty INTEGER NOT NULL,
  due_date DATE NOT NULL,
  destination VARCHAR(120) NOT NULL,
  status VARCHAR(24) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE production_plan ADD COLUMN IF NOT EXISTS planned_start DATE;
ALTER TABLE production_plan ADD COLUMN IF NOT EXISTS planned_start_time TIME;
CREATE TABLE IF NOT EXISTS robot_config (
  id INTEGER PRIMARY KEY,
  recipe VARCHAR(40) NOT NULL,
  speed_pct INTEGER NOT NULL,
  enabled BOOLEAN NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS robot_bridge_status (
  id INTEGER PRIMARY KEY,
  state VARCHAR(40) NOT NULL,
  detail VARCHAR(200) NOT NULL,
  completed_cycles INTEGER NOT NULL,
  plc_connected BOOLEAN NOT NULL,
  action_available BOOLEAN NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE production_plan ADD COLUMN IF NOT EXISTS created_by VARCHAR(100);
ALTER TABLE production_plan ADD COLUMN IF NOT EXISTS approved_by VARCHAR(100);
ALTER TABLE production_plan ADD COLUMN IF NOT EXISTS approved_at TIMESTAMP;
ALTER TABLE material_lot ADD COLUMN IF NOT EXISTS received_by VARCHAR(100);
CREATE TABLE IF NOT EXISTS plan_order (
  plan_id BIGINT PRIMARY KEY REFERENCES production_plan(id),
  order_id BIGINT NOT NULL UNIQUE REFERENCES mes_order(id)
);
CREATE TABLE IF NOT EXISTS production_lot (
  lot_code VARCHAR(100) PRIMARY KEY,
  order_id BIGINT NOT NULL UNIQUE REFERENCES mes_order(id),
  product_sku VARCHAR(32) NOT NULL REFERENCES item_master(sku),
  target_qty INTEGER NOT NULL,
  launched_qty INTEGER NOT NULL DEFAULT 0,
  good_qty INTEGER NOT NULL DEFAULT 0,
  rejected_qty INTEGER NOT NULL DEFAULT 0,
  shipped_qty INTEGER NOT NULL DEFAULT 0,
  status VARCHAR(24) NOT NULL DEFAULT 'CREATED',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS shipment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_code VARCHAR(100) NOT NULL UNIQUE,
  order_id BIGINT NOT NULL UNIQUE REFERENCES mes_order(id),
  finished_lot_code VARCHAR(100) NOT NULL,
  destination VARCHAR(120) NOT NULL,
  quantity INTEGER NOT NULL,
  departed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE robot_config ADD COLUMN IF NOT EXISTS preview_requested BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS robot_step (
 step_no INTEGER PRIMARY KEY, step_name VARCHAR(80) NOT NULL,
 j1 DOUBLE PRECISION NOT NULL,j2 DOUBLE PRECISION NOT NULL,j3 DOUBLE PRECISION NOT NULL,
 j4 DOUBLE PRECISION NOT NULL,j5 DOUBLE PRECISION NOT NULL,j6 DOUBLE PRECISION NOT NULL,
 seconds DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS plc_telemetry (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sampled_at TIMESTAMP NOT NULL,
 order_id BIGINT,
 connected BOOLEAN NOT NULL,
 target_qty INTEGER NOT NULL,
 launched_count INTEGER NOT NULL,
 reject_count INTEGER NOT NULL,
 packed_count INTEGER NOT NULL,
 exit_count INTEGER NOT NULL,
 machine_state INTEGER NOT NULL,
 assembly_phase INTEGER NOT NULL,
 inspection_phase INTEGER NOT NULL,
 packing_phase INTEGER NOT NULL,
 mes_stop BOOLEAN NOT NULL,
 motor_running BOOLEAN NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_plc_telemetry_time ON plc_telemetry(sampled_at);
CREATE TABLE IF NOT EXISTS twin_robot_program (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program_json TEXT NOT NULL,
  saved_by VARCHAR(100) NOT NULL DEFAULT '',
  saved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS ai_inspection (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inspected_at TIMESTAMP NOT NULL,
 order_id BIGINT,
 seq INTEGER NOT NULL,
 source VARCHAR(20) NOT NULL,
 image VARCHAR(120) NOT NULL,
 true_label VARCHAR(30) NOT NULL,
 pred_label VARCHAR(30) NOT NULL,
 cause VARCHAR(30) NOT NULL,
 verdict_good BOOLEAN NOT NULL,
 p_defect DOUBLE PRECISION NOT NULL,
 confidence DOUBLE PRECISION NOT NULL,
 probs VARCHAR(600) NOT NULL,
 threshold DOUBLE PRECISION NOT NULL,
 model_version VARCHAR(40) NOT NULL,
 latency_ms INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ai_inspection_order ON ai_inspection(order_id, seq);
